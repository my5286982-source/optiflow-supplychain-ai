def normalize_lang(lang: str) -> str:
    return lang if lang in TRANSLATIONS else "ar"


def t(lang: str, key: str, **values: object) -> str:
    lang = normalize_lang(lang)
    template = TRANSLATIONS[lang].get(key, TRANSLATIONS["ar"].get(key, key))
    return template.format(**values) if values else template


def label(value: dict, lang: str) -> str:
    lang = normalize_lang(lang)
    return value.get(lang) or value.get("en") or value.get("ar") or ""


def money(value: float, lang: str) -> str:
    return f"{round(value):,} {t(lang, 'currency')}"
